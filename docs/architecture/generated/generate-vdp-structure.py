#!/usr/bin/env python3
"""Generate deterministic Work 1/2 inventories for SETUP-003.

This deliberately uses only the Python standard library plus Git and ripgrep.
It inventories the supplied official agon-vdp checkout without modifying it.
Build, compiler, symbol, and runtime analysis belong to later SETUP-003 work.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import sys


GENERATOR_VERSION = "1.0.0"
EXPECTED_ORIGIN = "https://github.com/AgonPlatform/agon-vdp"
EXPECTED_RELEASE_TAG = "v2.16.0"
EXPECTED_RELEASE_COMMIT = "c7ac293d2aa81ddfa693390549bcd909069c8fc3"
VDP_GL_TAG = "all-the-plots"
VDP_GL_COMMIT = "ac2dd5986daf496c43ae8e7fe41836274aec54a0"


def run(source: Path, *args: str) -> str:
    result = subprocess.run(
        args,
        cwd=source,
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    return result.stdout.strip()


def yaml_scalar(value: object) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return json.dumps(str(value), ensure_ascii=False)


def append_yaml_list(lines: list[str], key: str, values: list[str], indent: int = 0) -> None:
    prefix = " " * indent
    lines.append(f"{prefix}{key}:")
    if not values:
        lines[-1] += " []"
        return
    for value in values:
        lines.append(f"{prefix}  - {yaml_scalar(value)}")


def parse_dependencies(platformio: Path) -> list[dict[str, str]]:
    dependencies: list[dict[str, str]] = []
    in_lib_deps = False
    for raw_line in platformio.read_text(encoding="utf-8").splitlines():
        stripped = raw_line.strip()
        if stripped == "lib_deps =":
            in_lib_deps = True
            continue
        if not in_lib_deps:
            continue
        if not raw_line.startswith((" ", "\t")):
            break
        if not stripped or stripped.startswith(";"):
            continue
        if stripped.startswith("https://") and "#" in stripped:
            url, reference = stripped.rsplit("#", 1)
            if url == "https://github.com/AgonPlatform/vdp-gl.git" and reference == VDP_GL_TAG:
                dependencies.append(
                    {
                        "declaration": stripped,
                        "identity_kind": "immutable_tag",
                        "name": "AgonPlatform/vdp-gl",
                        "requested": reference,
                        "resolved_commit": VDP_GL_COMMIT,
                        "source": url,
                        "verified_against_remote_tags": "2026-08-20",
                    }
                )
                continue
            dependencies.append(
                {
                    "declaration": stripped,
                    "identity_kind": "unclassified_git_reference",
                    "name": "AgonPlatform/vdp-gl",
                    "requested": reference,
                    "source": url,
                }
            )
            continue
        match = re.fullmatch(r"([^@]+)@(.+)", stripped)
        if match:
            dependencies.append(
                {
                    "declaration": stripped,
                    "identity_kind": "version_range",
                    "name": match.group(1),
                    "requested": match.group(2),
                    "source": "PlatformIO registry",
                }
            )
            continue
        dependencies.append(
            {
                "declaration": stripped,
                "identity_kind": "unclassified",
                "name": stripped,
                "requested": stripped,
                "source": "platformio.ini",
            }
        )
    return dependencies


def line_count(data: bytes) -> int | None:
    if b"\x00" in data:
        return None
    if not data:
        return 0
    return data.count(b"\n") + (0 if data.endswith(b"\n") else 1)


def extension_for(path: str) -> str:
    name = Path(path).name
    suffix = Path(name).suffix.lower()
    if suffix:
        return suffix
    return "[none]"


def directory_for(path: str) -> str:
    parent = Path(path).parent.as_posix()
    return parent if parent != "." else "[root]"


def write_manifest(
    output: Path,
    source: Path,
    release_tag: str,
    commit: str,
    origin: str,
    commit_date: str,
    dirty: bool,
    git_files: list[str],
    rg_files: list[str],
    dependencies: list[dict[str, str]],
) -> None:
    git_version = run(source, "git", "--version")
    rg_version = run(source, "rg", "--version").splitlines()[0]
    python_version = sys.version.split()[0]
    lines = [
        "# Generated by docs/architecture/generated/generate-vdp-structure.py; do not hand-edit.",
        "schema_version: 1",
        "generator:",
        f"  name: {yaml_scalar('generate-vdp-structure')}",
        f"  version: {yaml_scalar(GENERATOR_VERSION)}",
        f"  path: {yaml_scalar('docs/architecture/generated/generate-vdp-structure.py')}",
        "  regeneration_command: >-",
        "    .venv/bin/python docs/architecture/generated/generate-vdp-structure.py --source",
        "    <official-agon-vdp-checkout>",
        "source:",
        f"  repository: {yaml_scalar(origin)}",
        f"  expected_repository: {yaml_scalar(EXPECTED_ORIGIN)}",
        f"  release_tag: {yaml_scalar(release_tag)}",
        f"  commit: {yaml_scalar(commit)}",
        f"  commit_date: {yaml_scalar(commit_date)}",
        f"  checkout_dirty: {yaml_scalar(dirty)}",
        "tools:",
        f"  python: {yaml_scalar(python_version)}",
        f"  git: {yaml_scalar(git_version)}",
        f"  ripgrep: {yaml_scalar(rg_version)}",
        "declared_dependencies:",
    ]
    for dependency in dependencies:
        lines.append(f"  - name: {yaml_scalar(dependency['name'])}")
        for key in (
            "declaration",
            "identity_kind",
            "source",
            "requested",
            "resolved_commit",
            "verified_against_remote_tags",
        ):
            if key in dependency:
                lines.append(f"    {key}: {yaml_scalar(dependency[key])}")
    lines.extend(
        [
            "inventory_checks:",
            f"  git_tracked_file_count: {len(git_files)}",
            f"  ripgrep_visible_file_count: {len(rg_files)}",
        ]
    )
    append_yaml_list(lines, "git_only", sorted(set(git_files) - set(rg_files)), 2)
    append_yaml_list(lines, "ripgrep_only", sorted(set(rg_files) - set(git_files)), 2)
    append_yaml_list(
        lines,
        "outputs",
        [
            "docs/architecture/generated/manifest.yaml",
            "docs/architecture/generated/files.yaml",
        ],
    )
    lines.append("scope:")
    append_yaml_list(lines, "completed_work", ["SETUP-003.1", "SETUP-003.2"], 2)
    append_yaml_list(
        lines,
        "excluded",
        ["build metadata", "compiler database", "symbols", "runtime analysis"],
        2,
    )
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_files(output: Path, source: Path, paths: list[str]) -> None:
    records: list[dict[str, object]] = []
    by_directory: dict[str, dict[str, int]] = {}
    by_extension: dict[str, dict[str, int]] = {}
    totals = {"files": 0, "bytes": 0, "lines": 0, "binary_files": 0}

    for relative in paths:
        data = (source / relative).read_bytes()
        lines = line_count(data)
        directory = directory_for(relative)
        extension = extension_for(relative)
        record = {
            "path": relative,
            "directory": directory,
            "extension": extension,
            "bytes": len(data),
            "lines": lines,
        }
        records.append(record)
        totals["files"] += 1
        totals["bytes"] += len(data)
        if lines is None:
            totals["binary_files"] += 1
        else:
            totals["lines"] += lines
        for table, key in ((by_directory, directory), (by_extension, extension)):
            summary = table.setdefault(key, {"files": 0, "bytes": 0, "lines": 0})
            summary["files"] += 1
            summary["bytes"] += len(data)
            if lines is not None:
                summary["lines"] += lines

    lines_out = [
        "# Generated by docs/architecture/generated/generate-vdp-structure.py; do not hand-edit.",
        "schema_version: 1",
        "line_count_rule: >-",
        "  Count newline-delimited text lines and count a final unterminated",
        "  line. Files containing NUL bytes have lines: null.",
        "totals:",
    ]
    for key in ("files", "bytes", "lines", "binary_files"):
        lines_out.append(f"  {key}: {totals[key]}")
    for heading, table in (("by_directory", by_directory), ("by_extension", by_extension)):
        lines_out.append(f"{heading}:")
        for key in sorted(table):
            lines_out.append(f"  - key: {yaml_scalar(key)}")
            for metric in ("files", "bytes", "lines"):
                lines_out.append(f"    {metric}: {table[key][metric]}")
    lines_out.append("files:")
    for record in records:
        lines_out.append(f"  - path: {yaml_scalar(record['path'])}")
        for key in ("directory", "extension", "bytes", "lines"):
            lines_out.append(f"    {key}: {yaml_scalar(record[key])}")
    output.write_text("\n".join(lines_out) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True, type=Path)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("docs/architecture/generated"),
    )
    args = parser.parse_args()
    source = args.source.resolve()
    output = args.output.resolve()

    if not (source / ".git").exists() or not (source / "platformio.ini").is_file():
        parser.error("--source must be an agon-vdp Git checkout")

    origin = run(source, "git", "remote", "get-url", "origin")
    if origin.removesuffix(".git") != EXPECTED_ORIGIN:
        parser.error(f"unexpected origin: {origin}")
    commit = run(source, "git", "rev-parse", "HEAD")
    if commit != EXPECTED_RELEASE_COMMIT:
        parser.error(
            f"HEAD {commit} is not approved release {EXPECTED_RELEASE_TAG} "
            f"({EXPECTED_RELEASE_COMMIT})"
        )
    tags_at_head = run(source, "git", "tag", "--points-at", "HEAD").splitlines()
    if EXPECTED_RELEASE_TAG not in tags_at_head:
        parser.error(f"HEAD is not tagged {EXPECTED_RELEASE_TAG}")
    commit_date = run(source, "git", "show", "-s", "--format=%cI", "HEAD")
    dirty = bool(run(source, "git", "status", "--porcelain"))
    git_files = sorted(run(source, "git", "ls-files").splitlines())
    rg_files = sorted(run(source, "rg", "--files", "--hidden", "-g", "!.git").splitlines())

    output.mkdir(parents=True, exist_ok=True)
    dependencies = parse_dependencies(source / "platformio.ini")
    write_manifest(
        output / "manifest.yaml",
        source,
        EXPECTED_RELEASE_TAG,
        commit,
        origin,
        commit_date,
        dirty,
        git_files,
        rg_files,
        dependencies,
    )
    write_files(output / "files.yaml", source, git_files)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
